// Writes ../THIRD_PARTY.md from package-lock.json, so versions and licences
// come from what is actually installed. Run with: npm run third-party
// tests/test_dashboard.py fails if the file falls behind package.json.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const read = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')
const lock = JSON.parse(read('../package-lock.json'))
const pkg = JSON.parse(read('../package.json'))

// "node_modules/a/node_modules/b" -> "b"
const nameOf = (path) => path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length)
const packages = Object.entries(lock.packages)
  .filter(([path]) => path)
  .map(([path, info]) => ({ name: nameOf(path), path, ...info }))

const row = ({ name, version, license }) =>
  `| \`${name}\` | ${version} | ${license ?? 'UNKNOWN'} | https://www.npmjs.com/package/${name} |`
const table = (rows) =>
  ['| Package | Version | Licence | Source |', '|---|---|---|---|', ...rows.map(row)].join('\n')
const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)

const topLevel = (name) => packages.find((p) => p.path === `node_modules/${name}`)
const direct = (names) => Object.keys(names).sort().map(topLevel)

// Platform binaries for other systems are listed in the lockfile but aren't
// installed here, and only the build tools use them
const allProduction = packages.filter((p) => !p.dev)
const skipped = allProduction.filter((p) => p.optional).length
const seen = new Set()
const production = allProduction
  .filter((p) => !p.optional)
  .filter((p) => {
    const key = `${p.name}@${p.version}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
  .sort(byName)

const components = readdirSync(new URL('../src/components/ui/', import.meta.url))
  .filter((file) => file.endsWith('.tsx'))
  .sort()

const out = `# Third-party components and libraries

Generated by \`frontend/scripts/third-party.mjs\` from \`frontend/package-lock.json\`.
Don't edit this file by hand; run \`npm run third-party\` in \`frontend/\` after changing dependencies.

This covers the dashboard in \`frontend/\` and the built copy in \`backend/static/app/\`. Python packages
are pinned in \`requirements.txt\` and aren't listed here. Each package's full licence text is in its npm
package. Nothing loads from a CDN at runtime: the page's scripts and styles are bundled and served by Flask.

## Components copied into this repository

Copied as source from the shadcn/ui registry (https://ui.shadcn.com, MIT licence) with the
\`shadcn\` ${topLevel('shadcn').version} command, style \`radix-nova\`, into \`frontend/src/components/ui/\`:

${components.map((file) => `- \`${file}\``).join('\n')}

The one change after copying: each file imports \`cn\` from \`@/lib/utils\` instead of the \`cn\` package.

\`frontend/src/lib/utils.ts\` holds the standard shadcn \`cn\` helper, built on \`clsx\` and \`tailwind-merge\`.

## Code from packages that ends up in the built stylesheet

\`shadcn/tailwind.css\` (shadcn, MIT), \`tw-animate-css\` and Tailwind's base styles are compiled into the
built CSS file. \`shadcn\` is a development dependency because only the build reads it.

## Direct dependencies

${table(direct(pkg.dependencies))}

## Direct development tools

Used to build, test and check the dashboard. Playwright also downloads a Chromium browser into its own
cache, outside this repository, for the screenshot script; it isn't redistributed.

${table(direct(pkg.devDependencies))}

## Full production dependency tree

Every package in the lockfile that isn't development-only, including what the direct dependencies pull
in (${production.length} packages; ${skipped} optional platform binaries left out).

${table(production)}
`
writeFileSync(new URL('../../THIRD_PARTY.md', import.meta.url), out)
console.log(`THIRD_PARTY.md: ${components.length} components, ${production.length} production packages`)
